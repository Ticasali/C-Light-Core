#include "vector.h"

#include <stdint.h>
#include <stdlib.h>
#include <assert.h>

void	*vector_init(uint32_t elem_size, uint64_t base_size)
{
	assert(base_size != 0);
	struct header *memory = (struct header *)malloc(HEADER_SIZE + elem_size * base_size);
	if (!memory)
		return (NULL);
	memory->elem_count = 0;
	memory->elem_max = base_size;
	return ((char *)memory + HEADER_SIZE);
}
