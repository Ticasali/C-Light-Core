#include "vector.h"

#include <string.h>
#include <assert.h>

void	*resize_no_free(void **vec, uint64_t new_size, uint64_t elem_size);

bool	vector_push(void **vec, void *data, uint64_t elem_count, uint64_t elem_size)
{
	assert(elem_count != 0);
	struct header	*header = (struct header *)(*(char **)vec - HEADER_SIZE);
	if (header->elem_max - header->elem_count < elem_count)
	{
		// Realloc, too small.
		void	*old_vec = resize_no_free(vec, (header->elem_count + (elem_count - 1)) * 2, elem_size); // We cannot use vector_resize, bc data could be the vector itself, and vector_resize free the old data.
		if (old_vec == NULL)
			return (false);
		header = (struct header *)(*(char **)vec - HEADER_SIZE);
		char	*new_pos = *(char **)vec + (elem_size * header->elem_count);
		memcpy(new_pos, data, (elem_count * elem_size));
		header->elem_count += elem_count;
		vector_free(old_vec);
		return (true);
	}
	header = (struct header *)(*(char **)vec - HEADER_SIZE);
	char	*new_pos = *(char **)vec + (elem_size * header->elem_count);
	memcpy(new_pos, data, (elem_count * elem_size));
	header->elem_count += elem_count;
	return (true);
}
