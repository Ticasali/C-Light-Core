#include "vector.h"

#include <string.h>
#include <assert.h>

void	*resize_no_free(void **vec, uint64_t new_size, uint64_t elem_size);

bool	vector_insert_pos(void **vec, void *data, uint64_t elem_count, uint64_t elem_size, uint64_t pos)
{
	assert(elem_count != 0);
	struct header	*header = (struct header *)(*(char **)vec - HEADER_SIZE);
	assert(pos <= header->elem_count);
	if (header->elem_max - header->elem_count < elem_count)
	{
		void	*old_vec = resize_no_free(vec, (header->elem_count + (elem_count - 1)) * 2, elem_size);
		if (!old_vec)
			return (false);
		header = (struct header *)(*(char **)vec - HEADER_SIZE);
		char	*new_pos = *(char **)vec + (elem_size * pos);
		memmove(new_pos + (elem_count * elem_size), new_pos, header->elem_count * elem_size);
		memcpy(new_pos, data, elem_count * elem_size);
		header->elem_count += elem_count;
		vector_free(old_vec);
		return (true);
	}
	header = (struct header *)(*(char **)vec - HEADER_SIZE);
	char	*new_pos = *(char **)vec + (elem_size * pos);
	memmove(new_pos + (elem_count * elem_size), new_pos, header->elem_count * elem_size);
	memcpy(new_pos, data, elem_count * elem_size);
	header->elem_count += elem_count;
	return (true);
}
